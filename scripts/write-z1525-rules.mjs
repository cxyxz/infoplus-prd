const reviewed = [];
for (const rule of bundle.rules) {
  const text = notes[rule.kind]?.[rule.id];
  if (!text) continue;
  reviewed.push({
    id: rule.id,
    kind: rule.kind,
    interpretation: text,
    sha256: createHash('sha256').update(rule.expression).digest('hex'),
  });
}

const missing = Object.entries(notes).flatMap(([kind, map]) =>
  Object.keys(map).filter(id => !reviewed.some(item => item.id === id && item.kind === kind))
    .map(id => `${kind}/${id}`));
if (missing.length) throw new Error(`未匹配的规则：${missing.join('、')}`);

await writeFile(`${directory}/reviewed-rules.json`, JSON.stringify(reviewed, null, 2) + '\n');
